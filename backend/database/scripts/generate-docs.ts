// Generates ER diagrams and the data dictionary from the live schema, so they cannot drift from it.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { RowDataPacket } from 'mysql2/promise';
import { MIGRATIONS_DIR, connectAdmin } from '../lib.ts';

const DOCS = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'docs');
const database = process.env.DB_NAME ?? 'cafe_platform';
const conn = await connectAdmin(database);
const q = async (sql: string) => (await conn.query<RowDataPacket[]>(sql, [database, 1]))[0];

const live = new Set((await conn.query<RowDataPacket[]>(`SELECT TABLE_NAME n FROM information_schema.TABLES WHERE TABLE_SCHEMA = ?`, [database]))[0].map((r) => r.n as string));
const domains: Array<{ title: string; tables: string[] }> = [];
for (const file of readdirSync(MIGRATIONS_DIR).filter((f) => f.endsWith('.sql')).sort()) {
  const tables = [...readFileSync(join(MIGRATIONS_DIR, file), 'utf8').matchAll(/^CREATE TABLE (\w+)/gm)].map((m) => m[1]!).filter((t) => live.has(t));
  if (tables.length) domains.push({ title: file.replace(/^\d+_|\.sql$/g, '').replace(/_/g, ' '), tables });
}

const fkRows = await q(`SELECT TABLE_NAME t, CONSTRAINT_NAME k, REFERENCED_TABLE_NAME p, GROUP_CONCAT(COLUMN_NAME ORDER BY ORDINAL_POSITION) c
  FROM information_schema.KEY_COLUMN_USAGE WHERE TABLE_SCHEMA = ? AND ? IS NOT NULL AND REFERENCED_TABLE_NAME IS NOT NULL GROUP BY TABLE_NAME, CONSTRAINT_NAME, REFERENCED_TABLE_NAME ORDER BY t, k`);
const COMMON = new Set(['users', 'languages', 'currencies', 'countries', 'cafes', 'media_assets', 'cafe_branches']);

let rel = `# Database Relationships\n\n> Generated by \`npm run db:docs\` from the live schema. Do not edit by hand.\n\n` +
  `Diagrams show relationships inside each domain, plus the links to other domains in the table beneath. ` +
  `Links to the very common tables (${[...COMMON].join(', ')}) are omitted from diagrams for legibility, but are listed.\n` +
  `A key shown as \`cafe_id,x\` is a composite tenant-safe foreign key.\n`;

for (const { title, tables } of domains) {
  const set = new Set(tables);
  const inside = fkRows.filter((f) => set.has(f.t) && set.has(f.p));
  const outside = fkRows.filter((f) => set.has(f.t) && !set.has(f.p));
  const seen = new Set<string>();
  const lines = inside.map((f) => {
    const line = `  ${f.p} ||--o{ ${f.t} : "${f.c}"`;
    if (seen.has(line)) return null;
    seen.add(line);
    return line;
  }).filter(Boolean);
  const linked = new Set(inside.flatMap((f) => [f.t, f.p]));
  for (const t of tables) if (!linked.has(t)) lines.push(`  ${t} {\n  }`);
  rel += `\n## ${title[0]!.toUpperCase()}${title.slice(1)}\n\n\`\`\`mermaid\nerDiagram\n${lines.join('\n')}\n\`\`\`\n`;
  if (outside.length) {
    rel += `\n| Table | Column(s) | References |\n|---|---|---|\n`;
    for (const f of outside) rel += `| ${f.t} | \`${f.c}\` | ${f.p} |\n`;
  }
}
writeFileSync(join(DOCS, 'DATABASE_RELATIONSHIPS.md'), rel);

const cols = await q(`SELECT TABLE_NAME t, COLUMN_NAME c, COLUMN_TYPE ty, IS_NULLABLE n, COLUMN_DEFAULT d, COLUMN_KEY k, EXTRA e
  FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = ? AND ? IS NOT NULL ORDER BY t, ORDINAL_POSITION`);
const idx = await q(`SELECT TABLE_NAME t, INDEX_NAME i, NON_UNIQUE u, GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX) c
  FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = ? AND ? IS NOT NULL GROUP BY TABLE_NAME, INDEX_NAME, NON_UNIQUE ORDER BY t, i`);
const trg = await q(`SELECT EVENT_OBJECT_TABLE t, TRIGGER_NAME n, ACTION_TIMING w, EVENT_MANIPULATION e
  FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = ? AND ? IS NOT NULL ORDER BY t, n`);

const esc = (v: unknown) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
let dict = `# Data Dictionary\n\n> Generated by \`npm run db:docs\` from the live schema. Do not edit by hand.\n`;
for (const { title, tables } of domains) {
  dict += `\n## ${title[0]!.toUpperCase()}${title.slice(1)}\n`;
  for (const table of tables.sort()) {
    dict += `\n### ${table}\n\n| Column | Type | Null | Default | Notes |\n|---|---|---|---|---|\n`;
    for (const c of cols.filter((r) => r.t === table)) dict += `| ${c.c} | \`${esc(c.ty)}\` | ${c.n === 'YES' ? 'yes' : ''} | ${esc(c.d)} | ${esc([c.k, c.e].filter(Boolean).join(' '))} |\n`;
    const indexes = idx.filter((r) => r.t === table && r.i !== 'PRIMARY');
    if (indexes.length) dict += `\nIndexes: ${indexes.map((r) => `\`${r.i}\`${r.u === 0 ? ' (unique)' : ''}: ${r.c}`).join('; ')}\n`;
    const triggers = trg.filter((r) => r.t === table);
    if (triggers.length) dict += `\nTriggers: ${triggers.map((r) => `\`${r.n}\` (${r.w} ${r.e})`).join('; ')}\n`;
  }
}
writeFileSync(join(DOCS, 'DATA_DICTIONARY.md'), dict);
console.log(`Wrote DATABASE_RELATIONSHIPS.md and DATA_DICTIONARY.md for ${domains.reduce((n, d) => n + d.tables.length, 0)} tables.`);
await conn.end();
